"""Doc 11 §6 (ENV=aws, prompt 22): `deploy/.env.aws` supplies its keys and wins over the process environment; no
token in `repr(Settings)`; absent file → admin off; the subs come from `cognito-users.json`; a mapping passed in
never discovers a developer's own files. Decision 1 (2026-10-11): on ENV=aws the one admin bearer is
`DEMO_ADMIN_BEARER`; the local per-service tokens are never used there."""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from demo_ui.config import Settings, read_cognito_users, read_env_file

pytestmark = pytest.mark.unit

API = "https://abc.execute-api.us-east-1.amazonaws.com"
OPEN = (
    "# generated by scripts/render_env.py\n"
    "TOWER_URL=https://runtime.example/mcp\n"
    f"BINDING_URL=https://d1.cloudfront.net\nBINDING_ADMIN_URL={API}\n"
    f"MOCK_URL={API}/carrier-admin\nALERTS_URL={API}\nWEB_CHAT_URL=https://d2.cloudfront.net\n"
    "DEMO_ADMIN_BEARER=demo-admin-123456\nTOWER_TABLE_PREFIX=att-aws-\nAWS_REGION=ca-central-1\n"
    "CARRIER_GATEWAY_AUTH=sigv4\n"
)
CLOSED = f"TOWER_URL=https://runtime.example/mcp\nBINDING_URL=https://d1.cloudfront.net\nMOCK_URL=\nALERTS_URL={API}\n"
TOKENS = ("demo-admin-123456",)
LOCAL_TOKENS = {"MOCK_ADMIN_TOKEN": "local-mock-1", "ALERTS_INTERNAL_BEARER": "local-internal-2",
                "BIND_ADMIN_TOKEN": "local-bind-3"}  # fmt: skip


def files(tmp_path: Path, env_text: str, users: object | None = None) -> dict[str, str]:
    (tmp_path / ".env.aws").write_text(env_text, encoding="utf-8")
    out = {"ENV": "aws", "DEMO_UI_AWS_ENV_FILE": str(tmp_path / ".env.aws")}
    if users is not None:
        (tmp_path / "users.json").write_text(json.dumps(users), encoding="utf-8")
        out["DEMO_UI_COGNITO_USERS"] = str(tmp_path / "users.json")
    return out


def test_the_file_wins_over_the_process_environment(tmp_path: Path) -> None:
    stale = {"MOCK_URL": "https://stale.example", "DEMO_ADMIN_BEARER": "stale-token", "AWS_REGION": "us-east-1",
             "TOWER_URL": "http://localhost:8080/mcp", **LOCAL_TOKENS}  # fmt: skip
    s = Settings.from_env({**stale, **files(tmp_path, OPEN, {"asish": "sub-a", "mom": "sub-m"})})
    assert s.aws_env_loaded and s.mock_url == f"{API}/carrier-admin" and s.demo_admin_bearer == TOKENS[0]
    assert s.tower_url == "https://runtime.example/mcp" and s.aws_region == "ca-central-1"
    assert s.binding_admin_base == API and s.binding_url == "https://d1.cloudfront.net"
    assert s.table_prefix == "att-aws-"
    # decision 1: every admin-path client sends DEMO_ADMIN_BEARER on AWS, never a local token (e.g. the internal one)
    assert s.mock_bearer == s.alerts_admin_bearer == s.binding_admin_bearer == TOKENS[0]
    assert s.admin_on and s.carrier_enabled and s.sms_enabled and s.binding_admin_enabled and s.macros_enabled
    assert s.admin_label == "admin on" and s.personas == ("asish",)
    assert s.user_ids == {"asish": "sub-a", "mom": "sub-m"}
    assert not any(t in repr(s) for t in TOKENS) and "sub-a" not in repr(s)
    assert set(TOKENS) <= set(s.secrets())


def test_keys_outside_the_list_are_not_taken_from_the_file(tmp_path: Path) -> None:
    s = Settings.from_env({**files(tmp_path, OPEN + "DEMO_UI_TOKEN=x\nREF_AGENT=gpt\n")})
    assert s.ui_token is None and s.ref_agent == "auto"


def test_closed_path_or_no_file_means_admin_off(tmp_path: Path) -> None:
    s = Settings.from_env(files(tmp_path, CLOSED))
    assert not s.admin_on and not s.carrier_enabled and not s.sms_enabled and not s.binding_admin_enabled
    assert s.admin_label == "admin off" and "admin path closed: see Ops → Admin path" in s.carrier_off_reason
    absent = Settings.from_env({"ENV": "aws", "DEMO_UI_AWS_ENV_FILE": str(tmp_path / "nope"), "MOCK_URL": ""})
    assert not absent.aws_env_loaded and not absent.admin_on


def test_macros_need_the_subs(tmp_path: Path) -> None:
    s = Settings.from_env(files(tmp_path, OPEN))
    assert s.carrier_enabled and not s.macros_enabled
    assert "make cognito-users ENV=aws" in (s.macros_off_reason or "")
    assert s.user_ids == {"asish": "user-asish", "mom": "user-mom"}
    s = Settings.from_env(
        files(tmp_path, OPEN.replace(f"BINDING_ADMIN_URL={API}\n", ""), {"asish": "a", "mom": "m"})
    )
    assert not s.macros_enabled and "make outputs ENV=aws" in (s.macros_off_reason or "")
    assert not s.binding_admin_enabled  # never the CloudFront BINDING_URL with the admin bearer


def test_without_demo_admin_bearer_the_admin_path_is_off_even_with_local_tokens(tmp_path: Path) -> None:
    text = OPEN.replace("DEMO_ADMIN_BEARER=demo-admin-123456\n", "")
    s = Settings.from_env({**LOCAL_TOKENS, **files(tmp_path, text + "".join(f"{k}={v}\n" for k, v in LOCAL_TOKENS.items()),
                                                   {"asish": "a", "mom": "m"})})  # fmt: skip
    assert not s.admin_on and not s.carrier_enabled and not s.sms_enabled and not s.binding_admin_enabled
    assert s.mock_bearer is None and s.alerts_admin_bearer is None and s.binding_admin_bearer is None


@pytest.mark.parametrize(
    "users",
    [
        {"asish": "user-asish", "mom": "user-mom"},
        {"asish": "a"},
        ["a", "m"],
        {"asish": "x y", "mom": "m"},
        {"asish": "a", "mom": "a"},
    ],
)
def test_users_that_are_not_two_subs_are_refused(tmp_path: Path, users: object) -> None:
    p = tmp_path / "u.json"
    p.write_text(json.dumps(users), encoding="utf-8")
    assert read_cognito_users(p) is None
    p.write_text("{nope", encoding="utf-8")
    assert read_cognito_users(p) is None
    assert read_cognito_users(None) is None


def test_a_mapping_never_discovers_the_checkouts_files(tmp_path: Path) -> None:
    (tmp_path / "deploy").mkdir()
    (tmp_path / "mk").mkdir()
    (tmp_path / "Makefile").write_text("all:\n")
    (tmp_path / "deploy" / ".env.aws").write_text(OPEN, encoding="utf-8")
    env = {"ENV": "aws", "DEMO_UI_CHECKOUT": str(tmp_path), "MOCK_URL": ""}
    assert Settings.from_env(env).aws_env_loaded is False
    found = Settings.from_env(env, discover_files=True)
    assert found.aws_env_loaded and found.admin_on and found.checkout == tmp_path


def test_env_file_parser(tmp_path: Path) -> None:
    p = tmp_path / "e"
    p.write_text('# c\n\nA=1\r\nB="two words"\nC=\nnot a pair\nD=x=y\n', encoding="utf-8")
    assert read_env_file(p) == {"A": "1", "B": "two words", "C": "", "D": "x=y"}


def test_local_is_unchanged_by_the_aws_keys() -> None:
    s = Settings.from_env({"BIND_ADMIN_TOKEN": "bt-123456789", "BINDING_ADMIN_URL": "http://x",
                           "DEMO_ADMIN_BEARER": "dab-123456789", **LOCAL_TOKENS})  # fmt: skip
    assert s.local and s.admin_label is None and s.binding_admin_enabled and s.macros_enabled
    assert s.user_ids == {"asish": "user-asish", "mom": "user-mom"}
    assert (s.mock_bearer, s.alerts_admin_bearer, s.binding_admin_bearer) == (
        "local-mock-1", "local-internal-2", "local-bind-3")  # fmt: skip
